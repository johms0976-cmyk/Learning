/* Where each letter sits, so the guide lines and the box are right.
   tall   = uses the top line (capitals, b d f h k l t)
   tail   = goes below the baseline (g j p q y)          */
function wiExtent(ch) {
  const caps = ch === ch.toUpperCase() && /[A-Z]/.test(ch);
  const tall = caps || 'bdfhklt'.includes(ch);
  const tail = 'gjpqy'.includes(ch);
  return { tall, tail };
}
