#!/usr/bin/env node
/* ============================================================
   WORD LAND · PICTURE SHEET
   ------------------------------------------------------------
   Rebuilds img/pics/index.html — every drawing in img/pics/,
   laid out for a grown-up to look through and argue with.

       node tools/make-pic-sheet.js

   Same idea as tools/make-manifest.sh: the sheet is GENERATED,
   never edited by hand, so it can never drift from what is
   actually in the folder. Run it after adding drawings, and
   commit the result if you want to view it on Pages.

   It also reads PICTURE out of js/wordland-pictures.js and
   reports the two ways the set can be wrong:

     · a drawing in the folder that no word points at — dead
       weight, or a typo in the PICTURE key
     · a word pointing at a drawing that is not there — a
       broken image on a child's screen

   Neither is fatal. pictureHTML() falls back to the emoji when
   a file is missing, exactly like a missing recording falls
   back to the computer voice. But you want to know.
   ============================================================ */

const fs   = require('fs');
const path = require('path');

const ROOT  = path.join(__dirname, '..');
const PICS  = path.join(ROOT, 'img', 'pics');
const OUT   = path.join(PICS, 'index.html');

/* ── what is on disk ──────────────────────────────────────── */
let files = [];
try {
  files = fs.readdirSync(PICS).filter(f => f.endsWith('.svg')).sort();
} catch (e) {
  console.error('No img/pics/ folder yet — nothing to do.');
  process.exit(0);
}

/* ── what the code asks for ───────────────────────────────────
   Read rather than require: wordland-pictures.js expects the
   data file to be loaded first, and we only want one table. */
const wanted = new Map();          // WORD -> filename
try {
  const src = fs.readFileSync(path.join(ROOT, 'js', 'wordland-pictures.js'), 'utf8');
  const block = /const\s+PICTURE\s*=\s*\{([\s\S]*?)\n\};/.exec(src);
  if (block) {
    const line = /([A-Z_]+)\s*:\s*['"]([^'"]+)['"]/g;
    let m;
    while ((m = line.exec(block[1]))) wanted.set(m[1], path.basename(m[2]));
  }
} catch (e) { /* no pictures file — just show the folder */ }

const have    = new Set(files);
const claimed = new Set([...wanted.values()]);
const orphans = files.filter(f => wanted.size && !claimed.has(f));
const broken  = [...wanted.entries()].filter(([w, f]) => !have.has(f));

/* ── the page ─────────────────────────────────────────────── */
const wordOf = f => {
  for (const [w, file] of wanted) if (file === f) return w.toLowerCase();
  return f.slice(0, -4);
};

const cells = files.map(f => {
  const svg = fs.readFileSync(path.join(PICS, f), 'utf8').trim()
    .replace(/width="120" height="120"/, 'width="100%" height="auto"');
  const tag = wanted.size && !claimed.has(f) ? ' <span class="warn">unused</span>' : '';
  return `<figure><div class="p">${svg}</div>` +
         `<figcaption>${wordOf(f)}${tag}</figcaption></figure>`;
}).join('');

const notes = [];
if (broken.length)  notes.push(`<p class="bad">${broken.length} word` +
  `${broken.length > 1 ? 's point' : ' points'} at a drawing that is not here: ` +
  broken.map(([w, f]) => `${w} &rarr; ${f}`).join(', ') + '</p>');
if (orphans.length) notes.push(`<p class="bad">${orphans.length} drawing` +
  `${orphans.length > 1 ? 's are' : ' is'} in the folder but not in PICTURE: ` +
  orphans.join(', ') + '</p>');

const html = `<!DOCTYPE html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>Word Land pictures</title>
<style>
body{margin:0;padding:32px;background:#faf8f4;color:#2b2b2b;
 font:16px/1.5 -apple-system,BlinkMacSystemFont,"Segoe UI",sans-serif}
h1{font-size:22px;font-weight:500;margin:0 0 6px}
p.sub{margin:0 0 16px;color:#6b6b6b;font-size:14px}
p.bad{margin:0 0 10px;color:#a8412f;font-size:14px}
label{display:inline-flex;gap:8px;align-items:center;margin-bottom:20px;
 font-size:14px;color:#6b6b6b;cursor:pointer}
.grid{display:grid;grid-template-columns:repeat(auto-fill,minmax(140px,1fr));gap:20px}
figure{margin:0;text-align:center}
.p{background:#fff;border:1px solid #e6e0d6;border-radius:12px;padding:14px;
 aspect-ratio:1;display:flex;align-items:center;justify-content:center}
figcaption{margin-top:8px;font-size:14px;color:#4a4a4a}
.warn{color:#a8412f;font-size:12px}
.small .p{padding:26px}
</style></head><body>
<h1>Word Land pictures</h1>
<p class="sub">${files.length} drawing${files.length === 1 ? '' : 's'} in img/pics/. Generated by tools/make-pic-sheet.js &mdash; do not edit by hand.</p>
${notes.join('')}
<label><input type="checkbox" onchange="document.querySelector('.grid').classList.toggle('small',this.checked)"> show at card size</label>
<div class="grid">${cells}</div>
</body></html>
`;

fs.writeFileSync(OUT, html);
console.log(`Wrote img/pics/index.html — ${files.length} drawings.`);
if (broken.length)  console.log(`  ${broken.length} pointing at a missing file.`);
if (orphans.length) console.log(`  ${orphans.length} in the folder but unused.`);
